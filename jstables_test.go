// TestJSTables generates the data tables of the JavaScript port (js/src/tables) from Go itself, so that the port
// decodes HTML entities exactly like html.UnescapeString and classifies characters with the same Unicode tables as
// the unicode package: the HTML entity table is read from the Go source of the html package, the Unicode ranges
// from the unicode package. Without -update the files are compared; the Unicode file is only compared when this
// Go toolchain has the Unicode version it was generated with.

const jsTablesDir = "js/src/tables"

func TestJSTables_Entities(t *testing.T) {
	src := filepath.Join(goRoot(t), "src", "html", "entity.go")
	data, err := os.ReadFile(src)
	if err != nil {
		t.Skipf("Go source of the html package not available: %v", err)
	}
	f, err := parser.ParseFile(token.NewFileSet(), src, data, 0)
	if err != nil {
		t.Fatal(err)
	}
	one := map[string]rune{}
	two := map[string][2]rune{}
	longest := -1
	ast.Inspect(f, func(n ast.Node) bool {
		switch x := n.(type) {
		case *ast.ValueSpec:
			for i, name := range x.Names {
				if name.Name == "longestEntityWithoutSemicolon" && i < len(x.Values) {
					if lit, ok := x.Values[i].(*ast.BasicLit); ok {
						longest, _ = strconv.Atoi(lit.Value)
					}
				}
			}
		case *ast.KeyValueExpr:
			key, ok := x.Key.(*ast.BasicLit)
			if !ok || key.Kind != token.STRING {
				return true
			}
			name, err := strconv.Unquote(key.Value)
			if err != nil {
				t.Fatal(err)
			}
			switch v := x.Value.(type) {
			case *ast.BasicLit:
				one[name] = charLit(t, v)
			case *ast.CompositeLit:
				if len(v.Elts) != 2 {
					t.Fatalf("entity2 %q: %d elements", name, len(v.Elts))
				}
				two[name] = [2]rune{charLit(t, v.Elts[0].(*ast.BasicLit)), charLit(t, v.Elts[1].(*ast.BasicLit))}
			}
		}
		return true
	})
	if len(one) < 2000 || len(two) < 50 || longest <= 0 {
		t.Fatalf("unexpected html/entity.go layout: %d entities, %d pairs, longest %d", len(one), len(two), longest)
	}
	repl := windows1252Table(t, filepath.Join(goRoot(t), "src", "html", "escape.go"))
	var b bytes.Buffer
	b.WriteString("// Code generated by jstables_test.go from the Go html package (entity.go, escape.go); DO NOT EDIT.\n\n")
	b.WriteString("/** Code points that numeric references &#128; to &#159; stand for (Windows-1252). */\n")
	b.WriteString("export const WINDOWS_1252 = [")
	for i, r := range repl {
		if i > 0 {
			b.WriteString(", ")
		}
		fmt.Fprintf(&b, "0x%x", r)
	}
	b.WriteString("];\n\n")
	b.WriteString("/** Longest entity name html.UnescapeString accepts without its semicolon. */\n")
	fmt.Fprintf(&b, "export const LONGEST_ENTITY_WITHOUT_SEMICOLON = %d;\n\n", longest)
	fmt.Fprintf(&b, "/** Number of names ENTITY_DATA holds once expanded. */\nexport const ENTITY_COUNT = %d;\n\n", len(one))
	b.WriteString("/**\n")
	b.WriteString(" * Entities by code point, separated by |: the base-36 distance from the previous code point, \":\", then the\n")
	b.WriteString(" * names. A name stands for name; — with a trailing ! also for the bare name (legacy entities), with a\n")
	b.WriteString(" * trailing ~ for the bare name only.\n")
	b.WriteString(" */\n")
	b.WriteString("export const ENTITY_DATA =\n")
	groups, cps := entityGroups(one)
	prev := rune(0)
	writeEntries(&b, cps, func(k string) string {
		cp := groups[k].cp
		e := strconv.FormatInt(int64(cp-prev), 36) + ":" + strings.Join(groups[k].names, ",")
		prev = cp
		return e
	})
	b.WriteString("/** name:hex,hex (two code points), separated by |. */\n")
	b.WriteString("export const ENTITY2_DATA =\n")
	writeEntries(&b, sortedKeys(two), func(k string) string {
		return k + ":" + strconv.FormatInt(int64(two[k][0]), 16) + "," + strconv.FormatInt(int64(two[k][1]), 16)
	})
	checkGenerated(t, filepath.Join(jsTablesDir, "entities.ts"), b.Bytes(), nil)
}

type entityGroup struct {
	cp    rune
	names []string
}

// entityGroups groups the entities by code point (keys are the code points as fixed-width hex, so that sorting the
// keys sorts the code points). A legacy entity, valid with and without its semicolon, is written once.
func entityGroups(one map[string]rune) (map[string]*entityGroup, []string) {
	groups := map[string]*entityGroup{}
	for _, name := range sortedKeys(one) {
		cp := one[name]
		var enc string
		switch base, semi := strings.CutSuffix(name, ";"); {
		case semi && one[base] == cp:
			enc = base + "!"
		case semi:
			enc = base
		case one[name+";"] == cp:
			continue // written with its ; form
		default:
			enc = name + "~"
		}
		key := fmt.Sprintf("%08x", cp)
		if groups[key] == nil {
			groups[key] = &entityGroup{cp: cp}
		}
		groups[key].names = append(groups[key].names, enc)
	}
	return groups, sortedKeys(groups)
}

// windows1252Table reads html.replacementTable from the Go source.
func windows1252Table(t *testing.T, src string) []rune {
	t.Helper()
	f, err := parser.ParseFile(token.NewFileSet(), src, nil, 0)
	if err != nil {
		t.Skipf("Go source of the html package not available: %v", err)
	}
	var out []rune
	ast.Inspect(f, func(n ast.Node) bool {
		vs, ok := n.(*ast.ValueSpec)
		if !ok || len(vs.Names) != 1 || vs.Names[0].Name != "replacementTable" || len(vs.Values) != 1 {
			return true
		}
		for _, e := range vs.Values[0].(*ast.CompositeLit).Elts {
			out = append(out, charLit(t, e.(*ast.BasicLit)))
		}
		return false
	})
	if len(out) != 32 {
		t.Fatalf("html.replacementTable: %d entries", len(out))
	}
	return out
}

// writeEntries writes entries joined by "|" as concatenated string literals of about 110 characters.
func writeEntries(b *bytes.Buffer, keys []string, entry func(string) string) {
	var line strings.Builder
	flush := func(last bool) {
		b.WriteString("  " + strconv.Quote(line.String()))
		if last {
			b.WriteString(";\n\n")
		} else {
			b.WriteString(" +\n")
		}
		line.Reset()
	}
	for i, k := range keys {
		if i > 0 {
			line.WriteByte('|')
		}
		line.WriteString(entry(k))
		if line.Len() > 110 && i < len(keys)-1 {
			flush(false)
		}
	}
	flush(true)
}

func charLit(t *testing.T, lit *ast.BasicLit) rune {
	t.Helper()
	if lit.Kind != token.CHAR {
		t.Fatalf("not a rune literal: %s", lit.Value)
	}
	r, _, _, err := strconv.UnquoteChar(lit.Value[1:len(lit.Value)-1], '\'')
	if err != nil {
		t.Fatal(err)
	}
	return r
}

func goRoot(t *testing.T) string {
	if out, err := exec.Command("go", "env", "GOROOT").Output(); err == nil {
		if r := strings.TrimSpace(string(out)); r != "" {
			return r
		}
	}
	t.Skip("go env GOROOT failed")
	return ""
}

// jsUnicodeTables: the tables the port needs, by the name it uses.
var jsUnicodeTables = []struct {
	name string
	is   func(rune) bool
}{
	{"LETTER", unicode.IsLetter},
	{"MN", func(r rune) bool { return unicode.Is(unicode.Mn, r) }},
	{"CF", func(r rune) bool { return unicode.Is(unicode.Cf, r) }},
	{"LATIN", func(r rune) bool { return unicode.Is(unicode.Latin, r) }},
	{"CYRILLIC", func(r rune) bool { return unicode.Is(unicode.Cyrillic, r) }},
	{"GREEK", func(r rune) bool { return unicode.Is(unicode.Greek, r) }},
	{"ARMENIAN", func(r rune) bool { return unicode.Is(unicode.Armenian, r) }},
	{"CHEROKEE", func(r rune) bool { return unicode.Is(unicode.Cherokee, r) }},
	{"VARIATION_SELECTOR", func(r rune) bool { return unicode.Is(unicode.Variation_Selector, r) }},
	{"OTHER_DEFAULT_IGNORABLE", func(r rune) bool { return unicode.Is(unicode.Other_Default_Ignorable_Code_Point, r) }},
	{"SPACE", unicode.IsSpace},
}

var unicodeVersionLine = regexp.MustCompile(`(?m)^export const UNICODE_VERSION = "([^"]+)";$`)

func TestJSTables_Unicode(t *testing.T) {
	var b bytes.Buffer
	b.WriteString("// Code generated by jstables_test.go from the Go unicode package; DO NOT EDIT.\n")
	b.WriteString("// Each table lists inclusive ranges as base-36 numbers: first,last,first,last…\n\n")
	fmt.Fprintf(&b, "export const UNICODE_VERSION = %q;\n\n", unicode.Version)
	for _, tb := range jsUnicodeTables {
		var parts []string
		for r := rune(0); r <= unicode.MaxRune; r++ {
			if !tb.is(r) {
				continue
			}
			lo := r
			for r+1 <= unicode.MaxRune && tb.is(r+1) {
				r++
			}
			parts = append(parts, strconv.FormatInt(int64(lo), 36), strconv.FormatInt(int64(r), 36))
		}
		fmt.Fprintf(&b, "export const %s =\n", tb.name)
		var line strings.Builder
		for i, p := range parts {
			if i > 0 {
				line.WriteByte(',')
			}
			line.WriteString(p)
			if line.Len() > 110 && i < len(parts)-1 {
				b.WriteString("  " + strconv.Quote(line.String()) + " +\n")
				line.Reset()
			}
		}
		b.WriteString("  " + strconv.Quote(line.String()) + ";\n\n")
	}
	checkGenerated(t, filepath.Join(jsTablesDir, "unicode.ts"), b.Bytes(), func(old []byte) bool {
		m := unicodeVersionLine.FindSubmatch(old)
		return m != nil && string(m[1]) == unicode.Version
	})
}

// checkGenerated writes (with -update) or compares a generated file. comparable, when set, tells whether the
// existing file can be compared with this toolchain's output.
func checkGenerated(t *testing.T, path string, got []byte, comparable func(old []byte) bool) {
	t.Helper()
	if *update {
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, got, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	want, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("%v (run go test -run TestJSTables -update)", err)
	}
	if comparable != nil && !comparable(want) {
		t.Skipf("%s was generated with another Unicode version than %s", path, unicode.Version)
	}
	if !bytes.Equal(got, want) {
		t.Fatalf("%s is stale: run go test -run TestJSTables -update", path)
	}
}
